"""Writes Source/SLua.ScriptEngine/EventSignatures.cs from the SLua runtime's builtins.txt.

usage: generate-event-signatures.py <path to the runtime's builtins.txt> <path of EventSignatures.cs to write>

Each "event name( type name, ... )" line of builtins.txt becomes one table entry holding the parameter types in
order. The engine reads the key positions from this table when it turns posted event arguments into values, and
EventSignatureTests fails when the table and the runtime's list disagree, so run this again after a runtime update.
"""
import re
import sys

LINE = re.compile(r"^event\s+(\w+)\(\s*(.*?)\s*\)\s*$")

HEADER = """/* Copyright (c) 2026 Legion Builds
 *
 * This Source Code Form is subject to the terms of the Mozilla Public
 * License, v. 2.0. If a copy of the MPL was not distributed with this
 * file, You can obtain one at https://mozilla.org/MPL/2.0/.
 */

// <auto-generated>
// Written by tools/slua-events/generate-event-signatures.py from the runtime's builtins.txt. Do not edit by hand.
// </auto-generated>

using System.Collections.Generic;

namespace SLua.ScriptEngine
{
    /// <summary>The parameter types of every event the runtime knows, by event name, in the runtime's order.</summary>
    internal static class EventSignatures
    {
        internal static readonly IReadOnlyDictionary<string, string[]> Parameters = new Dictionary<string, string[]>
        {
"""

FOOTER = """        };
    }
}
"""


def main(builtins, out):
    rows = []
    with open(builtins, encoding="utf-8") as f:
        for line in f:
            m = LINE.match(line.rstrip("\r\n"))
            if not m:
                continue
            params = [p.strip().split()[0] for p in m.group(2).split(",")] if m.group(2) else []
            rows.append((m.group(1), params))
    if not rows:
        sys.exit("no event lines found in " + builtins)
    body = "".join(
        '            ["%s"] = %s,\n' % (
            name, "new string[] { %s }" % ", ".join('"%s"' % t for t in params) if params else "new string[0]")
        for name, params in rows
    )
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER + body + FOOTER)
    print("wrote %d events to %s" % (len(rows), out))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
